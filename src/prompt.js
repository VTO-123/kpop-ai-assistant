/** 清洗用户输入：去控制字符、压空白、限长。 */
export function sanitizeGroup(raw) {
  if (typeof raw !== 'string') return '';
  const value = raw
    .replace(/[\u0000-\u001f\u007f]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!value) return '';
  return value.slice(0, 40);
}

